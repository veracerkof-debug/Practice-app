const BY_ID = new Map(FOLK.flatMap(([, list]) => list));
export const FOLK_IDS = [...BY_ID.keys()];
export const isFolk = (id) => BY_ID.has(id) || id === 'custom';

// Свой лад: до 12 ступеней, первая — тоника (0), по возрастанию, каждая — 0…1199 центов
export const CUSTOM_DEF = [0, 200, 350, 500, 700, 900, 1050];
export function cleanCustom(list) {
  const v = (Array.isArray(list) ? list : CUSTOM_DEF).map((x) => Math.round(+x)).filter((x) => Number.isFinite(x) && x >= 0 && x < 1200);
  const out = [...new Set([0, ...v])].sort((a, b) => a - b).slice(0, 12);
  return out.length > 1 ? out : CUSTOM_DEF.slice();
}

// Ступени лада в центах (народный или свой) или null — лад из обычных (theory.js)
export function folkCents(id, cfg = {}) {
  if (id === 'custom') return cleanCustom(cfg.custom);
  return BY_ID.get(id) || null;
}

// Подпись ноты с дробной высотой: ближайшая нота и стрелка — ↓ ниже, ↑ выше (от 5 центов)
export function microLabel(m, name) {
  const n = Math.round(m), d = m - n;
  return name(n) + (Math.abs(d) < 0.05 ? '' : d > 0 ? '↑' : '↓');
}
