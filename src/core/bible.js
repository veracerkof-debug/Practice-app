export const BOOKS = RAW.map(([code, name, abbr, chapters], i) => ({ code, name, abbr, chapters, nt: i >= 39, i }));
export const bookOf = (code) => BOOKS.find((b) => b.code === code) || null;
export const TOTAL_CHAPTERS = BOOKS.reduce((n, b) => n + b.chapters, 0); // 1189

// Все главы по порядку: ['GEN.1', 'GEN.2', …]
export const ALL = BOOKS.flatMap((b) => Array.from({ length: b.chapters }, (_, k) => b.code + '.' + (k + 1)));
export const chKey = (code, ch) => code + '.' + ch;
export const parseKey = (k) => { const [code, c] = String(k).split('.'); return { code, ch: +c }; };

// «Быт 1–3», «Пс 1», «Мф 5 — Мк 2» — список глав одной строкой (подряд идущие главы одной книги — диапазоном)
export function refText(keys) {
  const parts = [];
  keys.map(parseKey).forEach(({ code, ch }) => {
    const last = parts.at(-1);
    if (last && last.code === code && last.to === ch - 1) last.to = ch;
    else parts.push({ code, from: ch, to: ch });
  });
  return parts.map((p) => { const b = bookOf(p.code); return (b ? b.abbr : p.code) + ' ' + (p.from === p.to ? p.from : p.from + '–' + p.to); }).join('; ');
}

// Текст книги (кэш в памяти): массив глав, глава — массив стихов
const cache = new Map();
export function loadBook(code) {
  if (!cache.has(code)) {
    const url = new URL('bible/synodal/' + code + '.json', document.baseURI).href;
    cache.set(code, fetch(url).then((r) => { if (!r.ok) throw new Error('bible ' + code + ' ' + r.status); return r.json(); }).catch((e) => { cache.delete(code); throw e; }));
  }
  return cache.get(code);
}
